import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const bundle = async (entry) => {
  const result = await build({ entryPoints: [entry], bundle: true, write: false, format: "iife", target: "es2022", minify: true,
    alias: { "@modelcontextprotocol/ext-apps": "@modelcontextprotocol/ext-apps/app-with-deps" }, legalComments: "none" });
  return result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
};
const [website, app] = await Promise.all([bundle("ui-src/website.ts"), bundle("ui-src/metabolic-app.ts")]);
const css = readFileSync("ui-src/health.css", "utf8");
// Embedded MCP cards do not depend on a remote font request.
const appCss = css.replace(/^@import[^;]+;/, "");
const card = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>CLP Health result</title><style>${appCss}</style></head><body><main class="mcp-card"><p class="eyebrow">CLP HEALTH INTELLIGENCE</p><p id="status" role="status">Waiting for the tool result…</p><section id="result" hidden></section></main><script>${app}</script></body></html>`;
mkdirSync("src/web", { recursive: true });
writeFileSync("src/web/generated.ts", "// Generated by scripts/build-health-ui.mjs.\n" +
  `export const HEALTH_CSS = ${JSON.stringify(css)};\nexport const WEBSITE_JS = ${JSON.stringify(website)};\nexport const METABOLIC_UI_HTML = ${JSON.stringify(card)};\n`);
console.log("Built website client and MCP result card.");
