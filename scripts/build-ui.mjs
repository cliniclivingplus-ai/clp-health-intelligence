// Bundles ui-src/egfr-app.ts (official ext-apps SDK included) into one self-contained HTML string,
// written to src/tools/egfr/ui.generated.ts. Run: npm run build:ui
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import "./build-health-ui.mjs";

const result = await build({
  entryPoints: ["ui-src/egfr-app.ts"],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2022",
  minify: true,
  alias: { "@modelcontextprotocol/ext-apps": "@modelcontextprotocol/ext-apps/app-with-deps" },
  legalComments: "none"
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\/script");
const html = readFileSync("ui-src/egfr.html", "utf8").replace("<!--APP_SCRIPT-->", () => "<script>" + js + "</script>");
writeFileSync(
  "src/tools/egfr/ui.generated.ts",
  "// GENERATED by scripts/build-ui.mjs from ui-src/. Do not edit by hand.\nexport const EGFR_UI_HTML = " + JSON.stringify(html) + ";\n"
);
console.log("Wrote src/tools/egfr/ui.generated.ts (" + html.length + " chars)");
